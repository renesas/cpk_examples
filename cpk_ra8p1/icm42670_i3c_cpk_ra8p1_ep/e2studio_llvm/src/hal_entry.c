void inv_imu_sleep_us(uint32_t us)
{
	R_BSP_SoftwareDelay(us, BSP_DELAY_UNITS_MICROSECONDS);
}

static int imuReadReg(struct inv_imu_serif *serif, uint8_t reg, uint8_t *buf, uint32_t len)
{
	uint32_t err;

	(void)serif;

#if IMU_INTERFACE == IMU_USING_I2C
	err = IIC_ReadMemory(0x68, reg, 8, buf, (uint16_t)len);
	if (err) {
		LOG_E(__FUNCTION__, "IIC_ReadMemory failed: %u", err);
	}
#else
	err = I3C_ReadMemory(reg, buf, len);
	if (err) {
		LOG_E(__FUNCTION__, "I3C_ReadMemory failed: %u", err);
	}
#endif

	return (int)err;
}

static int imuWriteReg(struct inv_imu_serif *serif, uint8_t reg, const uint8_t *buf, uint32_t len)
{
	uint32_t err;

	(void)serif;

#if IMU_INTERFACE == IMU_USING_I2C
	err = IIC_WriteMemory(0x68, reg, 8, buf, (uint16_t)len);
	if (err) {
		LOG_E(__FUNCTION__, "IIC_WriteMemory failed: %u", err);
	}
#else
	err = I3C_WriteMemory(reg, buf, len);
	if (err) {
		LOG_E(__FUNCTION__, "I3C_WriteMemory failed: %u", err);
	}
#endif

	return (int)err;
}
