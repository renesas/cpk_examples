static int imuWriteReg(struct inv_imu_serif *serif, uint8_t reg, const uint8_t *buf, uint32_t len);

/*******************************************************************************************************************//**
 * main() is generated by the RA Configuration editor and is used to generate threads if an RTOS is used.  This function
 * is called by main() when no RTOS is used.
 **********************************************************************************************************************/
void hal_entry(void)
{
	/* TODO: add your own code here */
	int rc;

	perfc_init(false);
#if CONSOLE_CFG_USE_RTT == 0
	SEGGER_RTT_Init();
#endif
	CONSOLE_Init();

	/* Clean screen */
#if CONSOLE_CFG_USE_RTT
    puts(RTT_CTRL_RESET);
    puts(RTT_CTRL_CLEAR);
#else
    puts("\x1b[2J\x1b[H");
    puts("\x1B[0m");
#endif
    printf("FSP Version: %s\r\n", FSP_VERSION_STRING);

#if IMU_INTERFACE == IMU_USING_I2C
    IIC_Init();
#else
    I3C_Init();
#endif
    R_ICU_ExternalIrqOpen(g_external_irq31.p_ctrl, g_external_irq31.p_cfg);

	s_imu_serif.read_reg = imuReadReg;
	s_imu_serif.write_reg = imuWriteReg;
	s_imu_serif.max_read = 126;
	s_imu_serif.max_write = 126;
#if IMU_INTERFACE == IMU_USING_I2C
	s_imu_serif.serif_type = UI_I2C;
#else
	s_imu_serif.serif_type = UI_I3C;
#endif
	s_imu_serif.context = NULL;
	rc = inv_imu_init(&s_imu_device, &s_imu_serif, TestICMCallback);

	/* Wake up 2nd core if this is first core and we are inside a multicore project. */
#if (0 == _RA_CORE) && (1 == BSP_MULTICORE_PROJECT) && !BSP_TZ_NONSECURE_BUILD

#if BSP_TZ_SECURE_BUILD
    /* Take semaphore so 2nd core can clear it */
    R_BSP_IpcSemaphoreTake(&g_core_start_semaphore);
#endif

    R_BSP_SecondaryCoreStart();

#if BSP_TZ_SECURE_BUILD
    /* Wait for 2nd core to start and clear semaphore */
    while(FSP_ERR_IN_USE == R_BSP_IpcSemaphoreTake(&g_core_start_semaphore))
    {
        ;
    }
#endif
#endif

#if (1 == _RA_CORE) && (1 == BSP_MULTICORE_PROJECT) && BSP_TZ_SECURE_BUILD
    /* Signal to 1st core that 2nd core has started */
    R_BSP_IpcSemaphoreGive(&g_core_start_semaphore);
#endif

    if (rc) {
    	LOG_E(__FUNCTION__, "IMU bus/driver initialization failed: %d", rc);
    }
    else {
    	TestICM42670(&s_imu_device);
    }

    while (1) {
		R_IOPORT_PinWrite(g_ioport.p_ctrl, USER_LED, BSP_IO_LEVEL_HIGH);
		R_BSP_SoftwareDelay(500, BSP_DELAY_UNITS_MILLISECONDS);
		R_IOPORT_PinWrite(g_ioport.p_ctrl, USER_LED, BSP_IO_LEVEL_LOW);
		R_BSP_SoftwareDelay(500, BSP_DELAY_UNITS_MILLISECONDS);
	}

#if BSP_TZ_SECURE_BUILD
    /* Enter non-secure code */
    R_BSP_NonSecureEnter();
#endif
}

