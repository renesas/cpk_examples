void TIMER0_Callback(timer_callback_args_t *p_args)
{
	static uint32_t cnt = 0;

	if (p_args->event == TIMER_EVENT_CYCLE_END) {
		cnt++;
		if ((cnt % 5) == 0) {
			s_time_500ms = true;
		}
		if ((cnt % 10) == 0) {
			s_time_1s = true;
		}
		if (cnt == 0xF0000000) {
			cnt = 0;
		}
	}
}

