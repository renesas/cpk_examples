{
	uint32_t err;

	(void)serif;

	err = I2C_COMMS_WriteMem(&g_i2c_dev_icm42670, reg, 8, buf, (uint16_t)len);
	if (err) {
		LOG_E(__FUNCTION__, "IIC_WriteMemory failed: %u", err);
	}

	return (int)err;
}
