void ExternalIRQ_Callback(external_irq_callback_args_t *p_args)
{
	if (p_args->channel == 24) {
		s_irq_flag = 1;
	}
}

void Timer0_Callback(timer_callback_args_t *p_args)
{
	if (p_args->event == TIMER_EVENT_CYCLE_END) {
		s_time_cnt++;
	}
}

static void read_speed_test(void)
{
	float speed;
	int64_t time_start, time_end;
	usb_status_t usb_status;
	usb_event_info_t usb_event;

	uint8_t first = 1;
	uint8_t read_done = 0;
	uint32_t rec_len = 0;

	printf("Please input %" PRIu32 " bytes from USB terminal\r\n", USB_TEST_BYTES);
	while (rec_len < USB_TEST_BYTES) {
		read_done = 0;
		R_USB_Read(g_basic0.p_ctrl, s_usb_pack_buf, USB_PACK_SIZE, USB_CLASS_PCDC);
		while (read_done == 0) {
			R_USB_EventGet(&usb_event, &usb_status);
			switch (usb_status) {
			case USB_STATUS_READ_COMPLETE:
				read_done = 1;
				break;
			case USB_STATUS_REQUEST:
				if ((usb_event.setup.request_type & USB_BREQUEST) == USB_PCDC_SET_LINE_CODING) {
    			R_USB_PeriControlDataGet(g_basic0.p_ctrl, (uint8_t *)&s_line_coding, 0x07);
				}
				else if ((usb_event.setup.request_type & USB_BREQUEST) == USB_PCDC_GET_LINE_CODING) {
					R_USB_PeriControlDataSet(g_basic0.p_ctrl, (uint8_t *)&s_line_coding, 0x07);
				}
				else if ((usb_event.setup.request_type & USB_BREQUEST) == USB_PCDC_SET_CONTROL_LINE_STATE) {
					R_USB_PeriControlStatusSet(g_basic0.p_ctrl, USB_SETUP_STATUS_ACK);
				}
				break;
			default:
				break;
			}
		}
		if (first) {
			first = 0;
			time_start = get_system_ms();
		}
		rec_len += usb_event.data_size;
	}
	time_end = get_system_ms();
	if (time_end != time_start) {
		speed = (float)USB_TEST_BYTES / (float)(time_end - time_start) / 1024.0f * 1000.0f;
		printf("Read using time: %" PRId64 "ms, speed: %.2f KB/s\r\n", time_end - time_start, speed);
	}
	else {
		printf("USB_TEST_BYTES is too small\r\n");
	}
}

static void wait_usb_attach(void)
{
	FUSB303_Status status;

	printf("Wait USB attach as a sink...\r\n");

	FUSB303B_Check(&status);
	while (status.type != DETECT_TYPE_SINK) {
		if (s_irq_flag) {
			s_irq_flag = 0;
			FUSB303B_Check(&status);
		}
		if (s_time_cnt > 5000) {
			s_time_cnt = 0;
			printf("Wait USB attach as a sink...\r\n");
		}
	}

	printf("USB attach and as a sink\r\n");
}

static void write_speed_test(void)
{
	uint32_t i;
	float speed;
	int64_t time_start, time_end;
	usb_status_t usb_status;
	usb_event_info_t usb_event;

	memset(s_usb_pack_buf, 't', USB_PACK_SIZE);
	s_usb_pack_buf[USB_PACK_SIZE - 2] = '\r';
	s_usb_pack_buf[USB_PACK_SIZE - 1] = '\n';

	time_start = get_system_ms();
	for (i = 0; i < USB_PACK_CNT; i++) {
		R_USB_Write(g_basic0.p_ctrl, s_usb_pack_buf, USB_PACK_SIZE, USB_CLASS_PCDC);
		do {
			R_USB_EventGet(&usb_event, &usb_status);
			R_BSP_SoftwareDelay(1, BSP_DELAY_UNITS_MICROSECONDS);
		} while (usb_status != USB_STATUS_WRITE_COMPLETE);
	}
	time_end = get_system_ms();

	if (time_end != time_start) {
		speed = (float)USB_TEST_BYTES / (float)(time_end - time_start) / 1024.0f * 1000.0f;
		printf("Write using time: %" PRId64 "ms, speed: %.2f KB/s\r\n", time_end - time_start, speed);
	}
	else {
		printf("USB_TEST_BYTES is too small\r\n");
	}
}
